inline void inject_all() {
  for (const auto &f : FRAMES) {
    esphome::esp32_ble::BLEScanResult r{};
    const uint8_t mac[6] = {0xA4, 0xC1, 0x38, 0x00, 0x10, f.mac_last};
    memcpy(r.bda, mac, 6);
    r.ble_addr_type = 0;
    r.rssi = -60 - f.mac_last;
    uint8_t n = 0;
    size_t nl = strlen(f.name);
    r.ble_adv[n++] = 2;
    r.ble_adv[n++] = 0x01;
    r.ble_adv[n++] = 0x06;
    r.ble_adv[n++] = nl + 1;
    r.ble_adv[n++] = 0x09;
    memcpy(r.ble_adv + n, f.name, nl);
    n += nl;
    r.ble_adv[n++] = f.len + 1;
    r.ble_adv[n++] = 0xFF;
    memcpy(r.ble_adv + n, f.rec, f.len);
    n += f.len;
    r.adv_data_len = n;
    r.scan_rsp_len = 0;
    r.search_evt = ESP_GAP_SEARCH_INQ_RES_EVT;
    esphome::esp32_ble_tracker::global_esp32_ble_tracker->gap_scan_event_handler(r);
  }
}
