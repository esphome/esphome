#!/bin/bash
# make_certs.sh: write ext/httpstest/certs.h with a fresh self-signed EC certificate (CERT), its key (KEY) and an
# unrelated key (BAD_KEY). Run it in the scratch copy of this directory; the files are test material, never commit them.
D=$(cd "$(dirname "$0")" && pwd); W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 -nodes -days 3650 -subj /CN=httpstest \
  -keyout "$W/key.pem" -out "$W/cert.pem" 2> /dev/null || { echo "FAIL: openssl req"; exit 1; }
openssl ecparam -name prime256v1 -genkey -noout 2> /dev/null | openssl pkey -out "$W/bad.pem" || { echo "FAIL: openssl bad key"; exit 1; }
{
  echo "#pragma once"
  echo "// Generated by make_certs.sh for the HTTPS test component."
  for v in CERT:cert KEY:key BAD_KEY:bad; do
    printf 'inline constexpr const char %s[] = R"PEM(%s\n)PEM";\n' "${v%%:*}" "$(cat "$W/${v#*:}.pem")"
  done
} > "$D/ext/httpstest/certs.h"
echo "wrote $D/ext/httpstest/certs.h"
