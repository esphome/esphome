// MQTT JSON Key Constants for Home Assistant Discovery
//
// This file defines string constants used as JSON keys in MQTT discovery payloads
// for Home Assistant integration. These are used exclusively with ArduinoJson as:
//   root[MQTT_DEVICE_CLASS] = "temperature";
//
// Implementation Notes:
// - Constants are defined as macros wrapping ESPHOME_F() rather than constexpr variables
// - ESPHOME_F() expands to Arduino's F() macro on ESP8266, storing strings in flash (PROGMEM)
//   to save RAM. On other platforms, it returns the plain string literal.
// - ArduinoJson natively supports flash strings (__FlashStringHelper*) as JSON keys
// - These macros must ONLY be used as ArduinoJson keys - they are not regular C strings
//
// Abbreviations:
// - USE_MQTT_ABBREVIATIONS: When defined, uses shortened key names (e.g., "dev_cla" instead
//   of "device_class") to reduce message size. Home Assistant supports both forms.
//
// Note: Other MQTT_* constants in this component (e.g., MQTT_CLIENT_CONNECTED,
// MQTT_LEGACY_UNIQUE_ID_GENERATOR) are C++ enums defined in mqtt_client.h and
// mqtt_backend*.h - they are unrelated to these JSON key macros.

