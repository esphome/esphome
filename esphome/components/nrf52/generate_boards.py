"""Generate the board data in boards.py from the Zephyr board device trees.

Each board's device tree is run through the C preprocessor and parsed with Zephyr's devicetree
library, the same steps a firmware build takes.

Usage: python esphome/components/nrf52/generate_boards.py <sdk-version>=<zephyr-path>[,<nrf-path>] ...
"""

from __future__ import annotations

from collections.abc import Iterable, Iterator
from dataclasses import dataclass
from pathlib import Path
import re
import subprocess
import sys
import tempfile

from devicetree import dtlib
import yaml

# The SoC line of a hardware model v1 <board>_defconfig, such as CONFIG_SOC_NRF52840_QIAA=y
DEFCONFIG_SOC_RE = re.compile(r"^CONFIG_SOC_(NRF52\d+)_\w+=y$", re.MULTILINE)
CDC_ACM_COMPATIBLE = "zephyr,cdc-acm-uart"
# Searched in each devicetree root, in this order (cmake/modules/pre_dt.cmake). dts/vendor is
# new in Zephyr 4.x; missing directories are skipped as the build does.
INCLUDE_SUBDIRS = (
    "include",
    "include/zephyr",
    "dts/common",
    "dts/vendor",
    "dts/arm",
    "dts",
)

GENERATED_MARKER = (
    "# DO NOT EDIT BELOW THIS LINE. Generated by script/generate-nrf52-boards.py"
)


@dataclass(frozen=True)
class BoardTarget:
    """One board target (what `board:` takes) and the device tree file it builds with."""

    name: str
    soc: str
    dts: Path


@dataclass(frozen=True)
class BoardInfo:
    soc: str
    # Paths of the CDC ACM nodes the board enables on its own
    cdc_acm: tuple[str, ...]


def _hwmv2_targets(board_yml: Path) -> Iterator[BoardTarget]:
    """Yield the nRF52 targets of a board.yml (hardware model v2, Zephyr 3.7 and newer)."""
    data = yaml.safe_load(board_yml.read_text(encoding="utf-8"))
    boards = data.get("boards") or [data["board"]]
    for board in boards:
        name = board["name"]
        socs = board.get("socs", [])
        for soc in socs:
            soc_name = soc["name"]
            if not soc_name.startswith("nrf52"):
                continue
            qualifiers = [soc_name]
            qualifiers.extend(
                f"{soc_name}/{variant['name']}" for variant in soc.get("variants", [])
            )
            for qualifier in qualifiers:
                dts = board_yml.parent / f"{name}_{qualifier.replace('/', '_')}.dts"
                # A board with one SoC can omit the SoC from both its target and file name
                short = len(socs) == 1 and qualifier == soc_name
                if short and not dts.is_file():
                    dts = board_yml.parent / f"{name}.dts"
                if dts.is_file():
                    target = name if short else f"{name}/{qualifier}"
                    yield BoardTarget(target, soc_name, dts)


def _hwmv1_targets(board_dir: Path) -> Iterator[BoardTarget]:
    """Yield the nRF52 targets of a board directory (hardware model v1, before Zephyr 3.7).

    Each target has a <target>.dts and a <target>_defconfig that selects the SoC.
    """
    for dts in sorted(board_dir.glob("*.dts")):
        defconfig = board_dir / f"{dts.stem}_defconfig"
        if not defconfig.is_file():
            continue
        if match := DEFCONFIG_SOC_RE.search(defconfig.read_text(encoding="utf-8")):
            yield BoardTarget(dts.stem, match.group(1).lower(), dts)


def find_targets(boards_dir: Path) -> list[BoardTarget]:
    """Find the nRF52 board targets under the boards directory of a board root."""
    targets: list[BoardTarget] = []
    board_ymls = sorted(boards_dir.glob("**/board.yml"))
    for board_yml in board_ymls:
        targets.extend(_hwmv2_targets(board_yml))
    if not board_ymls:
        for board_dir in sorted(p for p in boards_dir.glob("arm/*") if p.is_dir()):
            targets.extend(_hwmv1_targets(board_dir))
    return targets


def _include_dirs(roots: Iterable[Path]) -> list[Path]:
    """The include directories a Zephyr build passes to the preprocessor for each devicetree
    root (see cmake/modules/pre_dt.cmake)."""
    dirs: list[Path] = []
    for root in roots:
        dirs.extend(root / sub for sub in INCLUDE_SUBDIRS)
    return [d for d in dirs if d.is_dir()]


def _is_okay(node: dtlib.Node) -> bool:
    status = node.props.get("status")
    return status is None or status.to_string() == "okay"


def read_board(target: BoardTarget, roots: list[Path]) -> BoardInfo:
    """Preprocess and parse the board device tree and pick out the data ESPHome uses."""
    with tempfile.TemporaryDirectory() as tempdir:
        preprocessed = Path(tempdir) / "board.dts"
        command = ["cpp", "-x", "assembler-with-cpp", "-nostdinc", "-undef", "-P"]
        command.append("-D__DTS__")
        # The board directory is a devicetree root too, so <board>/dts is searched
        for include_dir in _include_dirs([target.dts.parent, *roots]):
            command += ["-isystem", str(include_dir)]
        command += [str(target.dts), "-o", str(preprocessed)]
        subprocess.run(command, check=True)
        tree = dtlib.DT(str(preprocessed))

    cdc_acm = tuple(
        node.path
        for node in tree.node_iter()
        if "compatible" in node.props
        and CDC_ACM_COMPATIBLE in node.props["compatible"].to_strings()
        and _is_okay(node)
        and all(_is_okay(parent) for parent in _parents(node))
    )
    return BoardInfo(target.soc, cdc_acm)


def _parents(node: dtlib.Node) -> Iterator[dtlib.Node]:
    while (node := node.parent) is not None:
        yield node


def load_boards(roots: list[Path]) -> dict[str, BoardInfo]:
    """Read every nRF52 board of one SDK version. roots[0] is the Zephyr tree."""
    boards: dict[str, BoardInfo] = {}
    for root in roots:
        for target in find_targets(root / "boards"):
            # A board in a later root replaces one with the same name, as in a build
            boards[target.name] = read_board(target, roots)
    return boards


def render(versions: dict[str, dict[str, BoardInfo]]) -> str:
    """Render the generated part of boards.py, starting at GENERATED_MARKER."""
    lines = [
        GENERATED_MARKER,
        "# nRF Connect SDK version -> board -> data read from the board device tree",
        "BOARDS = {",
    ]
    for version, boards in sorted(versions.items(), key=lambda v: _version_key(v[0])):
        lines.append(f'    "{version}": {{')
        for name, info in sorted(boards.items()):
            lines.append(f'        "{name}": {{')
            lines.append(f'            "soc": "{info.soc}",')
            if info.cdc_acm:
                lines.append('            "cdc_acm": [')
                lines.extend(f'                "{path}",' for path in info.cdc_acm)
                lines.append("            ],")
            lines.append("        },")
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _version_key(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in version.split("."))


def replace_generated(content: str, generated: str) -> str:
    """Replace everything from GENERATED_MARKER on with the newly generated part."""
    head, marker, _ = content.partition(GENERATED_MARKER)
    if not marker:
        raise ValueError(f"boards.py has no line '{GENERATED_MARKER}'")
    return head + generated


def main() -> None:
    versions: dict[str, dict[str, BoardInfo]] = {}
    for argument in sys.argv[1:]:
        version, paths = argument.split("=", 1)
        versions[version] = load_boards([Path(p) for p in paths.split(",")])
    sys.stdout.write(render(versions))


if __name__ == "__main__":
    main()
