# Boards with a GPIO wired to their RESET pin: driving it low is a pin reset, which the factory
# bootloader takes as its cue to stay in DFU mode (Nordic's own USB DFU trigger does the same)
SELF_RESET_PINS = {
    "nrf52840dongle": "P0.19",
}

# Bootloaders whose layout has a SoftDevice and the Adafruit bootloader, between which the mcumgr OTA
# image slot is placed
MCUMGR_OTA_BOOTLOADERS = (
    BOOTLOADER_ADAFRUIT_NRF52_SD132,
    BOOTLOADER_ADAFRUIT_NRF52_SD140_V6,
    BOOTLOADER_ADAFRUIT_NRF52_SD140_V7,
)

NRF52840_FLASH_SIZE = 0x100000
# Room for MCUboot with USB serial recovery (about 44 KB) and future growth such as signing
MCUBOOT_PARTITION_SIZE = 0x10000
SETTINGS_PARTITION_SIZE = 0xA000

# The image slots are sized later, below the lowest section reserved above them
MCUBOOT_SECTIONS = [
    Section("mcuboot", 0x0, MCUBOOT_PARTITION_SIZE, "flash_primary"),
    Section(
        "settings_storage",
        NRF52840_FLASH_SIZE - SETTINGS_PARTITION_SIZE,
        SETTINGS_PARTITION_SIZE,
        "flash_primary",
    ),
]

