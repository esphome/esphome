"""Flashing with pyOCD through a CMSIS-DAP probe, such as the one built into Seeed XIAO nRF54 boards."""

import logging
import os
from pathlib import Path

import esphome.config_validation as cv
from esphome.const import CONF_OTA, CONF_PLATFORM, KEY_CORE, KEY_FRAMEWORK_VERSION
from esphome.core import CORE, EsphomeError
from esphome.framework_helpers import run_command_ok

from .const import (
    VARIANT_NRF54L15,
    VARIANT_NRF54LM20,
    VARIANT_NRF52832,
    VARIANT_NRF52840,
)
from .framework import (
    check_and_install,
    get_build_env,
    get_build_paths,
    get_nrf52_variant,
    unpatched_pyocd_nrf54lm20a_target,
)

# pyOCD's built-in target names
_PYOCD_TARGETS = {
    VARIANT_NRF52832: "nrf52832",
    VARIANT_NRF52840: "nrf52840",
    VARIANT_NRF54L15: "nrf54l",
    VARIANT_NRF54LM20: "nrf54lm20a",
}


# USB IDs of probes whose port names no CMSIS-DAP interface, as on Windows
_CMSIS_DAP_USB_IDS = {
    (0x2886, 0x0068),  # Seeed XIAO nRF54LM20A
}

_LOGGER = logging.getLogger(__name__)

# pyOCD user script that stops the watchdog of the nRF54L chips after connecting
_NRF54L_WATCHDOG_SCRIPT = Path(__file__).with_name("pyocd_nrf54l_watchdog.py")


def cmsis_dap_unique_id(port: str) -> str | None:
    """The unique ID of the CMSIS-DAP probe that provides ``port``, or None for other ports."""
    import serial.tools.list_ports as _list_ports

    port = os.path.realpath(port)
    for info in _list_ports.comports(include_links=True):
        if os.path.realpath(info.device) != port:
            continue
        if (info.vid, info.pid) not in _CMSIS_DAP_USB_IDS and not any(
            "CMSIS-DAP" in (text or "") for text in (info.product, info.interface)
        ):
            return None
        if not info.serial_number:
            _LOGGER.warning(
                "The CMSIS-DAP probe behind %s reports no serial number; with more than "
                "one probe connected, another one may be flashed",
                port,
            )
        return info.serial_number or ""
    return None


def can_upload_using_cmsis_dap() -> bool:
    """True when upload_using_cmsis_dap can run: the 'sdk-nrf' toolchain at 2.9.2 or newer."""
    return not CORE.using_toolchain_platformio and CORE.data[KEY_CORE][
        KEY_FRAMEWORK_VERSION
    ] >= cv.Version(2, 9, 2)


def _builds_mcuboot() -> bool:
    """True when the build has an MCUboot image, as zephyr_mcumgr OTA adds one."""
    # From the config, as upload runs without to_code()
    return any(
        ota.get(CONF_PLATFORM) == "zephyr_mcumgr"
        for ota in CORE.config.get(CONF_OTA, [])
    )


def _images(build_dir: Path) -> list[Path]:
    """The hex files that make up the firmware.

    Chosen by SDK version and by whether MCUboot is built, so a file left by another build is
    never picked and a missing part is an error rather than a partial flash.
    """
    framework_ver = CORE.data[KEY_CORE][KEY_FRAMEWORK_VERSION]
    if framework_ver < cv.Version(2, 9, 2):
        raise EsphomeError(
            "Flashing with pyOCD needs nRF52 framework version 2.9.2 or newer"
        )
    app_dir = build_dir / "zephyr" / "zephyr"
    if framework_ver < cv.Version(3, 4, 0):
        # Always generated by these versions, with MCUboot when it is built
        images = [build_dir / "merged.hex"]
    elif _builds_mcuboot():
        images = [
            build_dir / "mcuboot" / "zephyr" / "zephyr.hex",
            app_dir / "zephyr.signed.hex",
        ]
    else:
        images = [app_dir / "zephyr.hex"]
    if (missing := next((i for i in images if not i.is_file()), None)) is not None:
        raise EsphomeError(f"{missing} not found. Please compile first.")
    return images


def upload_using_cmsis_dap(unique_id: str | None = None) -> None:
    """Flash with pyOCD; unique_id picks the probe when more than one is connected."""
    variant = get_nrf52_variant()
    if (target := _PYOCD_TARGETS.get(variant)) is None:
        raise EsphomeError(f"Flashing {variant} with pyOCD is not supported")
    images = _images(CORE.relative_pioenvs_path(CORE.name))
    check_and_install()  # the Zephyr requirements install pyOCD, and it is patched
    paths = get_build_paths()
    env = get_build_env(None)
    pyocd = [str(paths["python_executable"]), "-m", "pyocd"]
    probe = ["-t", target] + (["-u", unique_id] if unique_id else [])
    cmd = [*pyocd, "flash", "--no-wait", *probe, "-e", "sector"]
    if variant in (VARIANT_NRF54L15, VARIANT_NRF54LM20):
        cmd += ["--script", str(_NRF54L_WATCHDOG_SCRIPT)]
    cmd += [str(image) for image in images]
    if not run_command_ok(cmd, env=env, stream_output=True):
        # pyOCD unlocks a locked chip by erasing it, then resets it in a way that faults the rest
        # of that connection; a new connection reaches the unlocked chip
        _LOGGER.warning(
            "Flashing failed, trying once more in case the chip was just unlocked"
        )
        if not run_command_ok(cmd, env=env, stream_output=True):
            if variant == VARIANT_NRF54LM20 and (
                unpatched := unpatched_pyocd_nrf54lm20a_target()
            ):
                raise EsphomeError(
                    f"pyOCD could not flash the device. {unpatched} does not have the "
                    "fixed nRF54LM20A flash algorithm that ESPHome installs, and the "
                    "original one faults while writing. This pyOCD version is not "
                    "supported yet; please report it."
                )
            raise EsphomeError(
                "pyOCD could not flash the device; its output above says why. If it says "
                "the chip is locked or reports a memory transfer fault, unlock and erase it "
                f"once with 'pyocd erase -t {target} --mass' and upload again. Not with "
                "'--chip': it leaves an nRF54L locked, as no firmware opens it at reset."
            )
