#pragma once

#include "epaper_spi_4bpp.h"

namespace esphome::epaper_spi {

/**
 * E Ink EL133UF1: 13.3" Spectra 6 panel (1200x1600, 4bpp) with two controller chips, one chip
 * select each: CS drives the left half of every row and CS1 the right half. Used by the T133A01
 * (Seeed reTerminal E1004) and the Inkplate 13 Spectra; Good Display sells it as GDEP133C02.
 *
 * Provides chip select routing, the init sequence replay (the table comes from the Python model,
 * with a chip mask on every command), the power, refresh and sleep commands, and transfer_data()
 * with a full path and a partial path that uses the PTLW window of each chip. Subclasses supply
 * reset(), and override refresh_screen()/deep_sleep() where their board differs.
 *
 * The partial path is used when the model enables partial_update and full_update_every is above 1.
 *
 * DC is driven low for every command byte and high for its data. The T133A01 needs that;
 * the Inkplate 13 Spectra ignores DC and takes the first byte after CS as the command.
 */
class EPaperEL133UF1 : public EPaper4bpp {
 public:
  using EPaper4bpp::EPaper4bpp;

  // Not named set_cs_pin: that would hide SPIDevice::set_cs_pin(), which this class does not use.
  void set_primary_cs_pin(GPIOPin *cs) { this->cs_pins_[0] = cs; }
  void set_secondary_cs_pin(GPIOPin *cs1) { this->cs_pins_[1] = cs1; }

  void setup() override;
  void dump_config() override;

 protected:
  static constexpr uint8_t CHIP_COUNT = 2;

  // Rows sent per transfer_data() call, so the main loop keeps running during a transfer.
  static constexpr size_t ROWS_PER_CHUNK = 16;

  // Bytes one chip receives per row. Sizes the stack row buffers; the Python models keep the
  // width within it.
  static constexpr size_t MAX_HALF_ROW_BYTES = 400;

  static constexpr uint8_t REG_DTM = 0x10;
  static constexpr uint8_t REG_DRF = 0x12;
  static constexpr uint8_t REG_PON = 0x04;
  static constexpr uint8_t REG_POF = 0x02;
  static constexpr uint8_t REG_DSLP = 0x07;   // deep sleep, with check code 0xA5
  static constexpr uint8_t REG_PTLW = 0x83;   // partial window
  static constexpr uint8_t REG_CMD66 = 0xF0;  // waveform select, required again before PTLW
  static constexpr uint8_t REG_CCSET = 0xE0;  // color set select, resent before every full transfer

  // Chip masks for write_command_to_chip_(); the mask of chip index i is 1 << i.
  static constexpr uint8_t CHIP_PRIMARY = 1;
  static constexpr uint8_t CHIP_SECONDARY = 2;
  static constexpr uint8_t CHIP_BOTH = 3;

  static constexpr uint8_t CMD66_V[6] = {0x49, 0x55, 0x13, 0x5D, 0x05, 0x10};
  // 4x4 window at the origin, for a chip outside the update region: both chips must complete
  // CMD66 -> PTLW -> DTM.
  static constexpr uint8_t NULL_PTLW[9] = {0x00, 0x00, 0x00, 0x07, 0x00, 0x00, 0x00, 0x01, 0x01};

  // TRF_START: no path chosen yet; transfer_data() picks one and returns here when done.
  // TRF_FULL: transfer_full_(), which tracks its position in current_data_index_.
  // Partial path: TRF_PARTIAL_SETUP -> TRF_PARTIAL_DATA -> TRF_PARTIAL_WAIT for each chip in turn.
  enum TransferSub {
    TRF_START,
    TRF_FULL,
    TRF_PARTIAL_SETUP,
    TRF_PARTIAL_DATA,
    TRF_PARTIAL_WAIT,
  };

  // The partial window of one chip, computed once per partial update by compute_ptlw_params_().
  struct PartialChipParams {
    bool needed{false};  // false: the chip is outside the update region and gets NULL_PTLW
    uint8_t ptlw[9]{};   // HRST(2), HRED(2), VRST(2), VRED(2), PT(1)
    int mem_col_off{0};  // byte offset of the window from the start of a row in buffer_
    int bytes_per_row{0};
    int row_start{0};  // first row to send (inclusive)
    int row_end{0};    // last row to send (inclusive)
  };

  bool transfer_data() override;
  void abort_transfer() override;

  /// Replays init_sequence_, generated by the Python model. A delay entry ends the call, so the
  /// main loop keeps running while the delay passes.
  bool initialise(bool partial) override;

  uint8_t color_to_native(Color color) override;
  void power_on() override;
  void power_off() override;
  /// Sends the refresh command with data byte 0x01, which the T133A01 uses.
  void refresh_screen(bool partial) override;
  void deep_sleep() override;

  /// Full-refresh transfer: each chip in turn streams its half of every row, with its CS held
  /// low across yields.
  bool transfer_full_();

  /// Send a command (and optional data) to one or both chips. chip: CHIP_PRIMARY/SECONDARY/BOTH.
  void write_command_to_chip_(uint8_t cmd, const uint8_t *data, size_t len, uint8_t chip);
  void write_command_to_chip_(uint8_t cmd, std::initializer_list<uint8_t> data, uint8_t chip) {
    this->write_command_to_chip_(cmd, data.begin(), data.size(), chip);
  }
  void write_command_to_chip_(uint8_t cmd, uint8_t chip) { this->write_command_to_chip_(cmd, nullptr, 0, chip); }

  /// Opens a DTM data stream to one chip (by index): selects it and sends the command. The
  /// stream stays open, with the chip selected, until end_data_().
  void start_data_(uint8_t chip);
  void end_data_(uint8_t chip);

  /// Fills ptlw_ from the dirty box. Returns false if the box is empty.
  bool compute_ptlw_params_();

  GPIOPin *cs_pins_[CHIP_COUNT]{};

  TransferSub transfer_sub_{TRF_START};
  uint8_t transfer_chip_{0};  // the chip the partial path is working on
  size_t transfer_row_{0};    // partial path only; the full path uses current_data_index_
  size_t init_index_{0};      // position in init_sequence_ while initialise() waits out a delay

  PartialChipParams ptlw_[CHIP_COUNT];
};

}  // namespace esphome::epaper_spi
