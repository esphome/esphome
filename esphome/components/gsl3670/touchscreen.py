CONFIG_SCHEMA = (
    touchscreen.TOUCHSCREEN_SCHEMA.extend(
        {
            cv.GenerateID(): cv.declare_id(GSL3670Touchscreen),
            cv.Optional(CONF_INTERRUPT_PIN): pins.internal_gpio_input_pin_schema,
            cv.Optional(CONF_RESET_PIN): pins.gpio_output_pin_schema,
        }
    )
    .extend(i2c.i2c_device_schema(0x40))
    .extend(cv.COMPONENT_SCHEMA)
)


# ---------------------------------------------------------------------------
# Code generation
# ---------------------------------------------------------------------------
async def to_code(config):
    var = cg.new_Pvariable(config[CONF_ID])
    await touchscreen.register_touchscreen(var, config)
    await i2c.register_i2c_device(var, config)

    if CONF_INTERRUPT_PIN in config:
        pin = await cg.gpio_pin_expression(config[CONF_INTERRUPT_PIN])
        cg.add(var.set_interrupt_pin(pin))

    if CONF_RESET_PIN in config:
        pin = await cg.gpio_pin_expression(config[CONF_RESET_PIN])
        cg.add(var.set_reset_pin(pin))

    #  Firmware table
    fw_array = cg.progmem_array(
        ID(config[CONF_ID].id + "_fw", type=GSL3670FwRecord),
        [
            cg.StructInitializer(
                GSL3670FwRecord,
                ("offset", offset),
                ("val", val),
            )
            for offset, val in _SEEED_FIRMWARE
        ],
    )
    cg.add(var.set_firmware(fw_array, len(_SEEED_FIRMWARE)))

    #  Config blob for gsl_DataInit
    cfg_array = cg.progmem_array(
        ID(config[CONF_ID].id + "_cfg", type=cg.uint32),
        _SEEED_CONFIG,
    )
    cg.add(var.set_config(cfg_array, len(_SEEED_CONFIG)))
