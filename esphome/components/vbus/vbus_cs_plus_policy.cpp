std::optional<SettingSpec> setting_at(size_t position) {
  if (position >= SETTING_COUNT)
    return std::nullopt;
  SettingSpec spec;
  progmem_memcpy(&spec, &SETTINGS[position], sizeof(spec));
  return spec;
}

std::optional<size_t> setting_position(uint16_t index) {
  size_t first = 0;
  size_t last = SETTING_COUNT;
  while (first < last) {
    const size_t middle = first + (last - first) / 2;
    const uint16_t candidate = progmem_read_uint16(&SETTINGS[middle].index);
    if (candidate == index)
      return middle;
    if (candidate < index) {
      first = middle + 1;
    } else {
      last = middle;
    }
  }
  return std::nullopt;
}

std::optional<SettingSpec> find_setting(uint16_t index) {
  const auto position = setting_position(index);
  return position.has_value() ? setting_at(*position) : std::nullopt;
}

