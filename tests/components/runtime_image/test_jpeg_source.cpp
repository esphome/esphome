class SourceImage : public RuntimeImage {
 public:
  explicit SourceImage(image::ImageType type = image::IMAGE_TYPE_RGB, int width = 0, int height = 0)
      : RuntimeImage(JPEG, type, image::TRANSPARENCY_OPAQUE, nullptr, false, width, height) {}
  size_t decoded_bytes() const { return this->decoded_bytes_; }
  int scale() const { return static_cast<const JpegDecoder *>(this->decoder_.get())->get_scale(); }
};

/// The file in memory; fails reads once fail_at bytes have been read
class MemorySource : public DecodeSource {
 public:
  MemorySource(const uint8_t *data, size_t size, size_t fail_at = SIZE_MAX)
      : data_(data), size_(size), fail_at_(fail_at) {}
  int32_t read(uint8_t *buf, uint32_t len) override {
    if (this->pos_ >= this->fail_at_)
      return -1;
    const size_t n = std::min<size_t>(len, this->size_ - this->pos_);
    memcpy(buf, this->data_ + this->pos_, n);
    this->pos_ += n;
    this->reads++;
    return static_cast<int32_t>(n);
  }
  bool seek(uint32_t position) override {
    if (position > this->size_)
      return false;
    this->pos_ = position;
    return true;
  }
  int reads{0};

 protected:
  const uint8_t *data_;
  size_t size_;
  size_t pos_{0};
  size_t fail_at_;
};

/// Hands out only the bytes delivered so far, like a download that is still arriving
class TrickleSource : public DecodeSource {
 public:
  TrickleSource(const uint8_t *data, size_t size, size_t delivered) : data_(data), size_(size), delivered_(delivered) {}
  int32_t read(uint8_t *buf, uint32_t len) override {
    const size_t n = std::min<size_t>(len, this->delivered_ - this->pos_);
    memcpy(buf, this->data_ + this->pos_, n);
    this->pos_ += n;
    return static_cast<int32_t>(n);
  }
  bool seek(uint32_t position) override {
    if (position > this->delivered_)
      return false;
    this->pos_ = position;
    return true;
  }
  void deliver(size_t len) { this->delivered_ = std::min(this->size_, this->delivered_ + len); }

 protected:
  const uint8_t *data_;
  size_t size_;
  size_t delivered_;
  size_t pos_{0};
};

static bool decode_fed(RuntimeImage &img, const uint8_t *data = JPEG_ROWS, size_t size = sizeof(JPEG_ROWS)) {
  std::vector<uint8_t> buffer(data, data + size);
  if (!img.begin_decode(buffer.size()))
    return false;
  if (img.feed_data(buffer.data(), buffer.size()) != static_cast<int>(buffer.size()))
    return false;
  return img.end_decode();
}

/// Decodes from a source a step at a time; returns the last result and counts the steps
static int decode_stepped(RuntimeImage &img, DecodeSource &source, int &steps, size_t size = sizeof(JPEG_ROWS)) {
  steps = 0;
  if (!img.begin_decode(size) || !img.decoder_supports_source())
    return DECODE_ERROR_UNSUPPORTED_FORMAT;
  int result = img.begin_source(&source);
  if (result != 0)
    return result;
  do {
    result = img.decode_step();
    steps++;
  } while (result == DECODE_STEP_MORE);
  if (result == DECODE_STEP_DONE && !img.end_decode())
    return DECODE_ERROR_INTERNAL_DECODER_ERROR;
  return result;
}

static std::vector<uint8_t> pixels(const RuntimeImage &img) {
  const uint8_t *start = img.get_data_start();
  return std::vector<uint8_t>(start, start + img.get_width_stride() * img.get_height());
}

TEST(JpegSourceDecode, SteppedDecodeMatchesFedDecode) {
  SourceImage fed;
  ASSERT_TRUE(decode_fed(fed));

  SourceImage stepped;
  MemorySource source(JPEG_ROWS, sizeof(JPEG_ROWS));
  int steps;
  ASSERT_EQ(decode_stepped(stepped, source, steps), DECODE_STEP_DONE);
  EXPECT_EQ(steps, 3);
  ASSERT_EQ(stepped.get_width(), 48);
  ASSERT_EQ(stepped.get_height(), 40);
  EXPECT_EQ(pixels(stepped), pixels(fed));
}

