TEST(JpegSourceDecode, ReleasePartWayThroughAProgressiveImageLetsTheNextDecodeStart) {
  SourceImage img;
  MemorySource first(JPEG_ROWS_PROGRESSIVE, sizeof(JPEG_ROWS_PROGRESSIVE));
  ASSERT_TRUE(img.begin_decode(sizeof(JPEG_ROWS_PROGRESSIVE)));
  ASSERT_EQ(img.begin_source(&first), 0);
  ASSERT_EQ(img.decode_step(), DECODE_STEP_MORE);
  img.release();

  MemorySource second(JPEG_ROWS_PROGRESSIVE, sizeof(JPEG_ROWS_PROGRESSIVE));
  int steps;
  EXPECT_EQ(decode_stepped(img, second, steps, sizeof(JPEG_ROWS_PROGRESSIVE)), DECODE_STEP_DONE);
}

TEST(JpegSourceDecode, CompletedDecodeCountsTheWholeImage) {
  SourceImage img;
  MemorySource source(JPEG_ROWS, sizeof(JPEG_ROWS));
  ASSERT_TRUE(img.begin_decode(sizeof(JPEG_ROWS)));
  ASSERT_EQ(img.begin_source(&source), 0);
  int result;
  while ((result = img.decode_step()) == DECODE_STEP_MORE) {
    EXPECT_EQ(img.decoded_bytes(), 0u);
  }
  ASSERT_EQ(result, DECODE_STEP_DONE);
  EXPECT_EQ(img.decoded_bytes(), sizeof(JPEG_ROWS));
}

TEST(JpegSourceDecode, SourceIsReadAsTheDecodeNeedsIt) {
  SourceImage img;
  MemorySource source(JPEG_ROWS, sizeof(JPEG_ROWS));
  int steps;
  ASSERT_EQ(decode_stepped(img, source, steps), DECODE_STEP_DONE);
  EXPECT_GE(source.reads, 2);
}

TEST(JpegSourceDecode, DecodersThatCannotReadASourceSaySo) {
  RuntimeImage img(BMP, image::IMAGE_TYPE_RGB, image::TRANSPARENCY_OPAQUE);
  ASSERT_TRUE(img.begin_decode(100));
  EXPECT_FALSE(img.decoder_supports_source());
  MemorySource source(JPEG_ROWS, sizeof(JPEG_ROWS));
  EXPECT_EQ(img.begin_source(&source), DECODE_ERROR_UNSUPPORTED_FORMAT);
  EXPECT_EQ(img.decode_step(), DECODE_ERROR_UNSUPPORTED_FORMAT);
}

TEST(JpegSourceDecode, SourceNeedsTheImageSize) {
  SourceImage img;
  MemorySource source(JPEG_ROWS, sizeof(JPEG_ROWS));
  // JPEGDEC needs the file size up front, and holds it in an int
  ASSERT_TRUE(img.begin_decode(0));
  EXPECT_EQ(img.begin_source(&source), DECODE_ERROR_INVALID_TYPE);
  img.release();
  ASSERT_TRUE(img.begin_decode(static_cast<size_t>(INT32_MAX) + 1));
  EXPECT_EQ(img.begin_source(&source), DECODE_ERROR_INVALID_TYPE);
}

TEST(JpegSourceDecode, StepWithoutADecodeIsRefused) {
  SourceImage img;
  EXPECT_EQ(img.decode_step(), DECODE_ERROR_INVALID_TYPE);
  ASSERT_TRUE(img.begin_decode(sizeof(JPEG_ROWS)));
  // begin_source() was never called
  EXPECT_EQ(img.decode_step(), DECODE_ERROR_INVALID_TYPE);
}

