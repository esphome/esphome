// One feed_data() call stops after a short time, so a large image is decoded over several calls
TEST(PngTimeLimit, LargeImageIsDecodedOverSeveralCalls) {
  RuntimeImage img(PNG, image::IMAGE_TYPE_RGB, image::TRANSPARENCY_OPAQUE);
  std::vector<uint8_t> data(PNG_SOLID, PNG_SOLID + sizeof(PNG_SOLID));
  ASSERT_TRUE(img.begin_decode(data.size()));

  size_t offset = 0;
  int calls = 0;
  while (offset < data.size() && calls < 1000) {
    const int consumed = img.feed_data(data.data() + offset, data.size() - offset);
    ASSERT_GT(consumed, 0);
    offset += consumed;
    calls++;
  }
  EXPECT_GT(calls, 1) << "the whole image was decoded in one call";
  ASSERT_EQ(offset, data.size());
  ASSERT_TRUE(img.end_decode());

  ASSERT_EQ(img.get_width(), 800);
  ASSERT_EQ(img.get_height(), 600);
  for (auto [x, y] : {std::pair{0, 0}, std::pair{400, 300}, std::pair{799, 599}}) {
    const Color pixel = img.get_pixel(x, y);
    EXPECT_EQ(pixel.r, 30);
    EXPECT_EQ(pixel.g, 120);
    EXPECT_EQ(pixel.b, 200);
  }
}

