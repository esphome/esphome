// Mirrors the OTA session: chunked input through the read callback, window as output
struct Session : OtaInflateState {
  const uint8_t *in;
  size_t in_len;
  size_t in_pos;
  size_t chunk;
  std::vector<uint8_t> out;
  uint8_t window[WINDOW];
};

static int read_cb(OtaInflateState *d) {
  auto *s = static_cast<Session *>(d);
  if (s->in_pos >= s->in_len)
    return -1;
  size_t n = std::min(s->chunk, s->in_len - s->in_pos);
  d->source = s->in + s->in_pos + 1;
  d->source_limit = s->in + s->in_pos + n;
  s->in_pos += n;
  return s->in[s->in_pos - n];
}

